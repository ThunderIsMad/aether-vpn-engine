//! `rotation-tests` — дом интеграционного теста ротации egress-узла (Phase 0, главный риск проекта).
//!
//! Рабочего кода в этом крейте нет и не планируется: только спецификации интеграционных тестов
//! в `tests/*.rs`, которые меряют **frame-слой** (`design/02-protocols.md` §1/§3/§4,
//! `design/05-roadmap.md` Phase 0). Байндинги в тестах — моки трейта `CoverBinding`
//! (trait objects, in-memory); сети в CI нет.
//!
//! Почему отдельный крейт, а не `crates/frame-session/tests/rotation.rs`: тест ротации сводит
//! `frame-session`, `crypto-core`, `key-coordinator`, `ticket-mint` и `transport-mux`, а
//! `frame-session` по `design/03-components.md` → «Порядок зависимостей для сборки» не тянет
//! никого (крейт транспортно-независим). Dev-зависимости этого крейта — тестовые: порядок
//! сборки рабочих крейтов не меняется.
//!
//! **Граница измерения:** тест меряет frame-слой, не payload-соединения. Разрыв прикладных
//! TCP/QUIC сменой source IP при ротации — ожидаемый эффект Phase 0 (`05-roadmap`, риск),
//! а не регресс. Per-flow pinning — Phase 1.
//!
//! **Статус:** реализации нет — только тесты, но сами тесты исполняемы. Клип `#[ignore]` снят
//! `impl-phase-driver` вместе с реализацией модулей: критерии каждого сценария зафиксированы
//! доккомментариями тестов, а проверяются assert'ами в их телах. Совместная сборка — в
//! `tests/harness/mod.rs` (адаптер `crypto-core` → `frame-session`, мок узла, мок сети
//! и драйвер ротации с окном перекрытия).

